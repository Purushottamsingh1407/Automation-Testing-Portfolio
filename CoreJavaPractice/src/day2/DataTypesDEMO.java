package day2;

public class DataTypesDEMO {

	public static void main(String[] args) {
//Numeric Data Types
		int a = 100, b = 200;
		System.out.println("The value of a is: " + a);
		System.out.println("The value of b is: " + b);
		System.out.println("The sum of a and b is: " + (a + b));

		byte by = 120;
		System.out.println("The value of by is: " + by);

		short sh = 250;
		System.out.println("The value of sh is: " + sh);

		long lo = 1235678978787l;
		System.out.println("The valuee of lo is: " + 10);

		// Decimal Data Types float and double
		float price = 123.4f;
		System.out.println("THE VALUE OF PRICE IS:" + price);

		double d = 123.456789;
		System.out.println("The value of d is: " + d);

		// Character Data Type
		char grad = 'b';
		System.out.println("The grad of student is:" + grad);

		// boolean Data Type
		boolean bool = true;
		System.out.println("The value of bool is: " + bool);

		// String Data Type
		String name = "John";

	}

}
