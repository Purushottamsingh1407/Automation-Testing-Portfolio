package day3;

public class AssignmentOperators {

	public static void main(String[] args) {
//Assigment operators
		int a = 10;
		// a=a+5;
		a += 5;
		System.out.println(a);

		int b = 15;
		b = b - 5;
		System.out.println(b);

		int c = 20;
		c = c * 2;
		System.out.println(c);

		int d = 20;
		d = d % 2;
		System.out.println(d);

	}

}
