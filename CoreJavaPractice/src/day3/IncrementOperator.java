package day3;

public class IncrementOperator {

	public static void main(String[] args) {
		/*
		 * int a=10; a++; System.out.println(a);
		 */
//Post increament
		/*
		 * int a=10; int res=a++; System.out.println(res);
		 */

//pre Increament		
		int a = 10;
		int res = ++a;
		System.out.println(res);

	}

}
