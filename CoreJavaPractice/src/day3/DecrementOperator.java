package day3;

public class DecrementOperator {

	public static void main(String[] args) {
		/*
		 * int a=100; a=a-1; System.out.println(a);
		 */

//Post Decremnet 
		int a = 100;
		a--;
		System.out.println(a);

//Post Increameent 
		int b = 100;
		int res = --b;
		System.out.println(res);

	}

}
